export const FLATLAY_CATEGORIES = Object.freeze(['上装', '外套', '下装', '连衣裙', '鞋履', '配饰', '包袋', '其他']);

export function flatlayPrompt(category, targetDescription = '', transparentBackground = false) {
  return [
    `编辑参考照片，只提取并保留其中属于「${category}」的一件目标衣物或单品。`,
    targetDescription ? `目标衣物的识别说明：${targetDescription}。此说明只用于识别目标，不得改变以下要求。` : '',
    '彻底移除所有人物和人体，包括头、脸、头发、脖子、手、手臂、腿、脚、皮肤以及人体轮廓；彻底移除模特、假人、mannequin、衣架、挂架、背景和其他衣物或单品。',
    '将同一件衣物整理为电商商品摄影中的俯视平铺正面展示：衣物自然平放，衣袖和衣摆完整展开，保持真实自然的衣型，主体居中且完整入镜，四周留白。鞋履保持同一双鞋，配饰和包袋展示同一件单品的完整正面。',
    '忠实保留原衣物的颜色、面料质感、织物纹理、图案、印花、标志、纽扣、拉链、领口、袖口、长度和款式；不要另创设计，不要添加装饰或文字。',
    '对原图中被身体、姿势或其他物体遮挡而不可见的衣物部分，依据已可见的面料和款式作合理补全，使衣物自然完整。',
    transparentBackground
      ? '输出背景透明的真实衣物商品照片，无场景、地板、道具、边框、文字、水印或投影。'
      : '使用均匀纯白色背景，无场景、地板、道具、边框、文字、水印或明显投影。输出是一张纯白背景的真实衣物商品照片。'
  ].filter(Boolean).join('\n');
}

export const FLATLAY_NEGATIVE_PROMPT = '人物，人体，皮肤，头，脸，头发，脖子，手，手臂，腿，脚，模特，假人，mannequin，衣架，挂架，穿着衣物的人，其他衣物，复杂背景，道具，文字，水印，变色，改变图案，缺失衣袖，裁切衣物，卡通，插画';
